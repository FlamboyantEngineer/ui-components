#!/usr/bin/env node
// Writes src/components/emoji-picker/emoji-data.ts from the Emojibase English dataset
// (emojibase-data, a development dependency): one compact string the picker parses on load.
//   node scripts/generate-emoji-data.mjs
//
// Format: lines separated by "\n". A line without "|" names the category of the lines after it;
// every other line is "<glyph>|<tone>|<label>|<shortcodes>|<keywords>", lists separated by ",".
// The trailing empty fields of a line are dropped. <tone> is empty for
// an emoji without skin tones, "1" when the tone modifier follows the first code point, and "2"
// when it also follows the last one (two people).

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const compact = require('emojibase-data/en/compact.json');
const shortcodes = require('emojibase-data/en/shortcodes/emojibase.json');
const { version } = JSON.parse(
  readFileSync(join(root, 'node_modules/emojibase-data/package.json'), 'utf8'),
);

const CATEGORIES = {
  0: 'smileys',
  1: 'people',
  3: 'nature',
  4: 'food',
  5: 'travel',
  6: 'activities',
  7: 'objects',
  8: 'symbols',
  9: 'flags',
};
const MODIFIERS = ['\u{1F3FB}', '\u{1F3FC}', '\u{1F3FD}', '\u{1F3FE}', '\u{1F3FF}'];
const VARIATION = '️';

function uniformSkin(emoji, modifier) {
  return emoji.skins.find((skin) => {
    const used = [...skin.unicode].filter((point) => MODIFIERS.includes(point));
    return used.length > 0 && used.every((point) => point === modifier);
  });
}

function toneRule(emoji, pattern) {
  const [first, ...rest] = [...emoji.unicode];
  const tail = (rest[0] === VARIATION ? rest.slice(1) : rest).join('');
  if (pattern === `${first}~${tail}`) return '1';
  if (pattern === `${first}~${tail}~`) return '2';
  throw new Error(`No tone rule for ${emoji.label}`);
}

function tone(emoji) {
  if (!emoji.skins) return '';
  const skins = MODIFIERS.map((modifier) => uniformSkin(emoji, modifier));
  if (skins.some((skin) => !skin)) throw new Error(`Missing a uniform tone for ${emoji.label}`);
  const pattern = skins[0].unicode.split(MODIFIERS[0]).join('~');
  const rule = toneRule(emoji, pattern);
  skins.forEach((skin, index) => {
    if (pattern.split('~').join(MODIFIERS[index]) !== skin.unicode) {
      throw new Error(`Inconsistent tones for ${emoji.label}`);
    }
  });
  return rule;
}

function line(emoji) {
  const codes = [shortcodes[emoji.hexcode] ?? []].flat();
  return [emoji.unicode, tone(emoji), emoji.label, codes.join(','), (emoji.tags ?? []).join(',')]
    .join('|')
    .replace(/\|+$/, '');
}

const lines = [];
for (const [group, category] of Object.entries(CATEGORIES)) {
  lines.push(category);
  const members = compact
    .filter((emoji) => String(emoji.group) === group)
    .sort((a, b) => a.order - b.order);
  for (const emoji of members) lines.push(line(emoji));
}

const source = `// Generated by scripts/generate-emoji-data.mjs from emojibase-data ${version} (MIT). Do not edit.

/** Every standard emoji in category order, in the compact form \`parseEmojiData\` reads. */
export const compactEmojiData = ${JSON.stringify(lines.join('\n'))};
`;
writeFileSync(join(root, 'src/components/emoji-picker/emoji-data.ts'), source);
console.log(`Wrote ${lines.length - Object.keys(CATEGORIES).length} emoji.`);
