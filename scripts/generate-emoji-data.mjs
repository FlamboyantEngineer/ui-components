#!/usr/bin/env node
// Writes the emoji picker's data from the Emojibase datasets (emojibase-data, a development
// dependency), then run `npm run format`:
//   node scripts/generate-emoji-data.mjs
//
// src/components/emoji-picker/emoji-data.ts holds every standard emoji with its English names, as
// one compact string the picker parses on load. Lines are separated by "\n". A line without "|"
// names the category of the lines after it; every other line is
// "<glyph>|<tone>|<label>|<shortcodes>|<keywords>|<version>", lists separated by ",". <tone> is
// empty for an emoji without skin tones, "1" when the tone modifier follows the first code point,
// and "2" when it also follows the last one (two people). <version> is the Emoji version that
// introduced it.
//
// src/components/emoji-picker/emoji-data-<locale>.ts holds another locale's names: one
// "<label>|<keywords>" line per emoji line of emoji-data.ts, in the same order. An empty label keeps
// the English one. emoji-locales.ts loads each of them as a separate chunk.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const dataDir = join(root, 'node_modules/emojibase-data');
const outDir = join(root, 'src/components/emoji-picker');
/** @type {Array<{ group?: number, order: number } & Record<string, unknown>>} */
const compact = require('emojibase-data/en/compact.json');
const versions = new Map(
  require('emojibase-data/en/data.json').map((emoji) => [emoji.hexcode, emoji.version]),
);
const shortcodes = require('emojibase-data/en/shortcodes/emojibase.json');
const { version } = JSON.parse(readFileSync(join(dataDir, 'package.json'), 'utf8'));
const header = `// Generated by scripts/generate-emoji-data.mjs from emojibase-data ${version} (MIT). Do not edit.`;

const CATEGORIES = {
  0: 'smileys',
  1: 'people',
  3: 'nature',
  4: 'food',
  5: 'travel',
  6: 'activities',
  7: 'objects',
  8: 'symbols',
  9: 'flags',
};
const MODIFIERS = ['\u{1F3FB}', '\u{1F3FC}', '\u{1F3FD}', '\u{1F3FE}', '\u{1F3FF}'];
const VARIATION = '️';

function uniformSkin(emoji, modifier) {
  return emoji.skins.find((skin) => {
    const used = [...skin.unicode].filter((point) => MODIFIERS.includes(point));
    return used.length > 0 && used.every((point) => point === modifier);
  });
}

function toneRule(emoji, pattern) {
  const [first, ...rest] = [...emoji.unicode];
  const tail = (rest[0] === VARIATION ? rest.slice(1) : rest).join('');
  if (pattern === `${first}~${tail}`) return '1';
  if (pattern === `${first}~${tail}~`) return '2';
  throw new Error(`No tone rule for ${emoji.label}`);
}

function tone(emoji) {
  if (!emoji.skins) return '';
  const skins = MODIFIERS.map((modifier) => uniformSkin(emoji, modifier));
  if (skins.some((skin) => !skin)) throw new Error(`Missing a uniform tone for ${emoji.label}`);
  const pattern = skins[0].unicode.split(MODIFIERS[0]).join('~');
  const rule = toneRule(emoji, pattern);
  skins.forEach((skin, index) => {
    if (pattern.split('~').join(MODIFIERS[index]) !== skin.unicode) {
      throw new Error(`Inconsistent tones for ${emoji.label}`);
    }
  });
  return rule;
}

/** Keywords as one field: a comma inside a keyword would split it, so it becomes a space. */
function keywords(emoji) {
  return (emoji.tags ?? []).map((tag) => tag.replace(/\s*,\s*/g, ' ').trim()).join(',');
}

function line(emoji) {
  const codes = [shortcodes[emoji.hexcode] ?? []].flat();
  const introduced = versions.get(emoji.hexcode);
  if (introduced === undefined) throw new Error(`No version for ${emoji.label}`);
  return [
    emoji.unicode,
    tone(emoji),
    emoji.label,
    codes.join(','),
    keywords(emoji),
    introduced,
  ].join('|');
}

function localeLine(emoji) {
  const text = `${emoji?.label ?? ''}|${emoji ? keywords(emoji) : ''}`;
  if (/[|\n]/.test(emoji?.label ?? '')) throw new Error(`A separator in ${emoji.label}`);
  return text.replace(/\|$/, '');
}

const ordered = [];
const lines = [];
for (const [group, category] of Object.entries(CATEGORIES)) {
  lines.push(category);
  const members = compact
    .filter((emoji) => String(emoji.group) === group)
    .sort((a, b) => a.order - b.order);
  for (const emoji of members) {
    ordered.push(emoji.hexcode);
    lines.push(line(emoji));
  }
}

writeFileSync(
  join(outDir, 'emoji-data.ts'),
  `${header}

/** Every standard emoji in category order, in the compact form \`parseEmojiData\` reads. */
export const compactEmojiData = ${JSON.stringify(lines.join('\n'))};
`,
);

const locales = readdirSync(dataDir)
  .filter((name) => name !== 'en' && existsSync(join(dataDir, name, 'compact.json')))
  .sort();
for (const locale of locales) {
  const byHexcode = new Map(
    require(`emojibase-data/${locale}/compact.json`).map((emoji) => [emoji.hexcode, emoji]),
  );
  const text = ordered.map((hexcode) => localeLine(byHexcode.get(hexcode))).join('\n');
  writeFileSync(
    join(outDir, `emoji-data-${locale}.ts`),
    `${header}

/** The ${locale} names and keywords of the standard emoji, one line per emoji of \`compactEmojiData\`. */
export const compactEmojiLocale = ${JSON.stringify(text)};
`,
  );
}

const property = (locale) => (/^[a-z]+$/.test(locale) ? locale : `'${locale}'`);
writeFileSync(
  join(outDir, 'emoji-locales.ts'),
  `${header}

/** Each bundled locale besides English, loading its emoji names and keywords as a separate chunk. */
const loaders = {
${locales.map((locale) => `  ${property(locale)}: () => import('./emoji-data-${locale}.js'),`).join('\n')}
};

/** A locale whose emoji names and keywords the picker bundles. */
export type EmojiLocale = 'en' | keyof typeof loaders;

/** Whether the picker bundles the emoji names and keywords of \`locale\`. */
export function isEmojiLocale(locale: string): locale is EmojiLocale {
  return locale === 'en' || Object.hasOwn(loaders, locale);
}

/** Loads the compact names and keywords of a bundled locale other than English. */
export function importEmojiLocale(locale: Exclude<EmojiLocale, 'en'>): Promise<string> {
  return loaders[locale]().then((module) => module.compactEmojiLocale);
}
`,
);

console.log(`Wrote ${ordered.length} emoji in English and ${locales.length} other locales.`);
